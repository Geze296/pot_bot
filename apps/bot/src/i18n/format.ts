/** Times are stored in UTC and shown in the league's time zone (hard rule 1). */
export function formatLocalTime(moment: Date, timeZone: string): string {
  return new Intl.DateTimeFormat("en-GB", {
    timeZone,
    weekday: "short",
    day: "numeric",
    month: "short",
    hour: "2-digit",
    minute: "2-digit",
    hour12: false,
  }).format(moment);
}
